CREATE DATABASE IF NOT EXISTS BANCO;
USE BANCO;

CREATE TABLE IF NOT EXISTS CLIENTE (
                                       ID INT AUTO_INCREMENT PRIMARY KEY,
                                       NOME VARCHAR(50) NOT NULL,
    CPF VARCHAR(11) NOT NULL UNIQUE,
    EMAIL VARCHAR(50) NOT NULL UNIQUE,
    CIDADE VARCHAR(50) NOT NULL,
    DATA_CADASTRO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

CREATE TABLE IF NOT EXISTS CONTA (
                                     ID INT AUTO_INCREMENT PRIMARY KEY,
                                     CLIENTE_ID INT NOT NULL,
                                     SALDO DECIMAL(15,2) NOT NULL DEFAULT 0 CHECK (SALDO >= 0),
    TIPO_CONTA ENUM('CORRENTE','POUPANCA') NOT NULL,
    STATUS ENUM('ATIVA','BLOQUEADA','ENCERRADA') NOT NULL DEFAULT 'ATIVA',
    DATA_ABERTURA DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE (ID)
    );

CREATE TABLE IF NOT EXISTS TRANSACAO (
                                         ID INT AUTO_INCREMENT PRIMARY KEY,
                                         CONTA_ORIGEM_ID INT NOT NULL,
                                         CONTA_DESTINO_ID INT,
                                         TIPO ENUM('SAQUE','DEPOSITO','TRANSFERENCIA') NOT NULL,
    VALOR DECIMAL(15,2) NOT NULL CHECK (VALOR > 0),
    DATA_TRANSFERENCIA DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (CONTA_ORIGEM_ID) REFERENCES CONTA (ID),
    FOREIGN KEY (CONTA_DESTINO_ID) REFERENCES CONTA (ID)
    );